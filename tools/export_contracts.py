"""Generate shared JSON Schema and TypeScript using installed Pydantic v2."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from api.contracts import ContractBundle


def ts(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(x) for x in node["enum"])
    if "anyOf" in node:
        return " | ".join(ts(x) for x in node["anyOf"])
    kind = node.get("type")
    if kind == "array":
        return f"Array<{ts(node['items'])}>"
    if kind == "object":
        return f"Record<string, {ts(node['additionalProperties'])}>"
    return {"string": "string", "integer": "number", "number": "number", "null": "null", "boolean": "boolean"}[kind]


schema = ContractBundle.model_json_schema()
schema_text = json.dumps(schema, indent=2) + "\n"
lines = ["// Generated by tools/export_contracts.py. Edit api/contracts.py instead."]
for name, definition in schema["$defs"].items():
    lines.append(f"export interface {name} {{")
    for key, node in definition["properties"].items():
        optional = "" if key in definition.get("required", []) else "?"
        lines.append(f"  {key}{optional}: {ts(node)};")
    lines.append("}\n")
outputs = {ROOT / "shared/contracts.schema.json": schema_text,
           ROOT / "web/src/generated/contracts.ts": "\n".join(lines)}
for path, content in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Stale generated contract: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
print("Contracts match." if "--check" in sys.argv else "Contracts generated.")
